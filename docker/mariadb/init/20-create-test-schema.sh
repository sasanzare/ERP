#!/usr/bin/env bash
set -euo pipefail

: "${MARIADB_ROOT_PASSWORD:?MARIADB_ROOT_PASSWORD is required}"
: "${DB_TEST_DATABASE:?DB_TEST_DATABASE is required}"
: "${DB_TEST_USERNAME:?DB_TEST_USERNAME is required}"
: "${DB_TEST_PASSWORD:?DB_TEST_PASSWORD is required}"

if [[ ! "$DB_TEST_DATABASE" =~ ^[a-z][a-z0-9_]*$ || ! "$DB_TEST_USERNAME" =~ ^[a-z][a-z0-9_]*$ ]]; then
    echo 'Test database and username must be lowercase SQL identifiers.' >&2
    exit 1
fi

if [[ ! "$DB_TEST_PASSWORD" =~ ^[A-Fa-f0-9]{64}$ ]]; then
    echo 'DB_TEST_PASSWORD must be a 64-character hexadecimal secret generated by scripts/Initialize-Local.ps1.' >&2
    exit 1
fi

MYSQL_PWD="$MARIADB_ROOT_PASSWORD" mariadb --protocol=socket --user=root <<SQL
CREATE DATABASE IF NOT EXISTS \`$DB_TEST_DATABASE\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '$DB_TEST_USERNAME'@'%' IDENTIFIED BY '$DB_TEST_PASSWORD';
ALTER USER '$DB_TEST_USERNAME'@'%' IDENTIFIED BY '$DB_TEST_PASSWORD';
GRANT ALL PRIVILEGES ON \`$DB_TEST_DATABASE\`.* TO '$DB_TEST_USERNAME'@'%';
SQL
